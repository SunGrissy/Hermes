logger = logging.getLogger("palace.llm")


def _robust_json_parse(text: str) -> dict:
    """Parse JSON from LLM output with tolerance for common formatting issues."""
    text = text.strip()
    if text.startswith("```"):
        text = re.sub(r"^```\w*\n?", "", text)
        text = re.sub(r"\n?```\s*$", "", text)
        text = text.strip()

    try:
        return json.loads(text)
    except json.JSONDecodeError:
        pass

    try:
        return json.loads(text, strict=False)
    except json.JSONDecodeError:
        pass

    start = text.find("{")
    end = text.rfind("}")
    if start >= 0 and end > start:
        candidate = text[start:end + 1]
        try:
            return json.loads(candidate, strict=False)
        except json.JSONDecodeError:
            pass
        cleaned = re.sub(r",\s*([}\]])", r"\1", candidate)
        try:
            return json.loads(cleaned, strict=False)
        except json.JSONDecodeError:
            pass
    else:
        cleaned = text

    repaired = _repair_unescaped_quotes(cleaned)
    try:
        return json.loads(repaired, strict=False)
    except json.JSONDecodeError:
        pass

    _dump_debug(text)
    raise json.JSONDecodeError("All parse attempts failed", text[:200], 0)


def _repair_unescaped_quotes(text: str) -> str:
    """Fix unescaped double quotes inside JSON string values.

    LLMs sometimes produce JSON like:  "text": "he said "hello" today"
    which should be:                    "text": "he said \\"hello\\" today"
    """
    result = []
    i = 0
    in_string = False
    while i < len(text):
        c = text[i]
        if c == '\\' and in_string:
            result.append(c)
            if i + 1 < len(text):
                i += 1
                result.append(text[i])
            i += 1
            continue
        if c == '"':
            if not in_string:
                in_string = True
                result.append(c)
            else:
                if _is_structural_quote(text, i):
                    in_string = False
                    result.append(c)
                else:
                    result.append('\\')
                    result.append('"')
            i += 1
            continue
        result.append(c)
        i += 1
    return ''.join(result)


def _is_structural_quote(text: str, pos: int) -> bool:
    """Determine if the quote at pos is a structural JSON quote (ending a string)
    or a stray quote inside a string value."""
    rest = text[pos + 1:pos + 20].lstrip()
    if not rest:
        return True
    next_ch = rest[0]
    if next_ch in (',', ':', '}', ']', '\n', '\r'):
        return True
    return False


def _dump_debug(text: str):
    """Save raw LLM response to debug file for analysis."""
    import os, time
    debug_dir = os.path.join(os.path.dirname(os.path.dirname(__file__)), "debug_output")
    os.makedirs(debug_dir, exist_ok=True)
    ts = time.strftime("%H%M%S")
    path = os.path.join(debug_dir, f"llm_raw_{ts}.txt")
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)
    logger.error("JSON parse failed. Raw response saved to %s (%d chars)", path, len(text))


class LLMProvider(ABC):
    @abstractmethod
    async def complete(self, system_prompt: str, user_prompt: str, schema: dict | None = None) -> dict:
        ...


