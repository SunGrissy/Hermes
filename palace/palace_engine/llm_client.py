# Mock provider — preset fixtures for testing
# ============================================================

class MockProvider(LLMProvider):
    def __init__(self):
        self._extraction = _build_extraction_presets()
        self._assessment = _build_assessment_presets()

    async def complete(self, system_prompt: str, user_prompt: str, schema: dict | None = None) -> dict:
        if self._is_extraction(system_prompt):
            kw = self._match_topic(user_prompt)
            return self._extraction.get(kw, self._extraction.get("default", {}))

        role_id = self._identify_role(system_prompt)
        kw = self._match_topic(user_prompt)
        key = f"{role_id}:{kw}"
        if key in self._assessment:
            return self._assessment[key]
        return self._assessment.get(f"{role_id}:default", {"role_id": role_id, "verdict": "pass",
                "perspective_summary": "No preset available", "issue_assessments": []})

    def _is_extraction(self, prompt: str) -> bool:
        if "\u6587\u6863\u7ed3\u6784\u4e0e\u8fde\u8d2f\u6027\u6559\u7ec3" in prompt:
            return True
        if "\u7248\u672c\u6392\u5e03\u7ed3\u6784\u5206\u6790\u5e08" in prompt:
            return True
        if "layer_overview" in prompt and "checklist" in prompt:
            return True
        return False

    def _identify_role(self, prompt: str) -> str:
        head = prompt[:200]
        if "\u7ba1\u7ebf\u4e3b\u7b56" in head or "PLD" in head.split("\n")[0]:
            return "pld"
        if "\u7ba1\u7ebf\u4f53\u9a8c" in head or "PLE" in head.split("\n")[0]:
            return "ple"
        if "\u7ba1\u7ebf\u6280\u672f" in head or "PLT" in head.split("\n")[0]:
            return "plt"
        if "PMO" in head or "\u7248\u672c PMO" in head or "\u7248\u672c\u7ea7\u522b\u7684 PMO" in head:
            return "pmo"
        return "unknown"

    def _match_topic(self, prompt: str) -> str:
        if "\u9526\u6807" in prompt or "\u6708\u8d5b" in prompt:
            return "tournament"
        if "\u7248\u672c\u5185\u5bb9\u6982\u8981" in prompt or "\u7248\u672c\u89c4\u5212" in prompt:
            return "version"
        if "\u5f00\u706b" in prompt or "\u6311\u6218" in prompt:
            return "ops_event"
        if "\u968f\u5fc3\u8d2d" in prompt or "\u793c\u5305" in prompt or "\u795e\u541b" in prompt:
            return "shop_event"
        if "\u56db\u8c61" in prompt or "\u89d2\u529b" in prompt:
            return "contest_event"
        return "default"


